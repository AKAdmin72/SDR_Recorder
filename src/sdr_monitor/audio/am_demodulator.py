"""AM-демодуляция огибающей."""

from __future__ import annotations

import numpy as np


class AmDemodulator:
    """Огибающая AM = модуль комплексного (уже перенесённого на 0 Гц) канала.

    Полностью безсостоятельная (stateless) операция: у нас уже есть
    квадратурное (I/Q) представление сигнала с приёмника, поэтому огибающая
    берётся напрямую как модуль — в отличие от классического приёмника с
    вещественным сигналом, которому для этого потребовалось бы преобразование
    Гильберта или диодный детектор.
    """

    def process(self, channel_samples: np.ndarray) -> np.ndarray:
        return np.abs(channel_samples).astype(np.float32)
